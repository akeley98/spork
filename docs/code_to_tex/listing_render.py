"""Output formats of the listing generator (third stage).

* ``NAME.tex``   -- all versions in one file, for ``\\sporkListing`` (see
  ``latex/code_to_tex_support.tex``);
* ``NAME.N.txt`` -- displayed text of version N;
* ``NAME.N.dbg`` -- displayed text plus ``⟦...⟧`` formatting annotations.
"""

from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
from typing import Optional

from .listing_layout import BACKTICK, CODE, MATH, MONO, ListingLayout, RenderLine
from .listing_parse import COLOR_MACROS, ELIDE, MarkDirective

ELLIPSIS = "..."

# Backticks and single quotes are intentionally not escaped: runs of 2+
# backticks in comments reach TeX as is, so ``quotes'' typeset as curly quotes.
_TEX_ESCAPES = {
    " ": "~",
    "#": r"\#",
    "$": r"\$",
    "%": r"\%",
    "&": r"\&",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"{\textasciitilde}",
    "^": r"{\textasciicircum}",
    "\\": r"{\textbackslash}",
}


@dataclass(frozen=True)
class _Run:
    """Maximal span of characters with the same color (None = uncolored)."""

    color: Optional[str]
    start: int
    end: int


def _runs(line: RenderLine) -> list[_Run]:
    runs: list[_Run] = []
    for i, color in enumerate(line.colors):
        if runs and runs[-1].color == color:
            runs[-1] = _Run(color, runs[-1].start, i + 1)
        else:
            runs.append(_Run(color, i, i + 1))
    return runs


def _marks_by_column(line: RenderLine) -> dict[int, list[MarkDirective]]:
    result: dict[int, list[MarkDirective]] = defaultdict(list)
    for col, mark in line.marks:
        result[col].append(mark)
    return result


def _walk(line: RenderLine, run_fn, mark_fn) -> list[str]:
    """Shared skeleton: marks at run boundaries go *between* runs (outside any
    box); marks strictly inside a run are handled by ``run_fn``."""
    marks = _marks_by_column(line)
    out: list[str] = []
    for run in _runs(line):
        out.extend(mark_fn(m) for m in marks.get(run.start, ()))
        out.append(run_fn(run, marks))
    out.extend(mark_fn(m) for m in marks.get(len(line.text), ()))
    return out


# ---------------------------------------------------------------------------
# TeX
# ---------------------------------------------------------------------------


def tex_mark(mark: MarkDirective) -> str:
    return rf"\sporkListingMark{{{mark.name}}}{{{mark.xshift or ''}}}{{{mark.yshift or ''}}}"


def _tex_chars(line: RenderLine, run: _Run, marks, in_box: bool) -> str:
    r"""One run of same-colored characters.  Comment text goes in one
    ``\sporkComment`` group per run (``\textsf`` in a box, keeping the box
    colors); backticked text inside it in ``\texttt`` (keeping the comment or
    box color), closed and reopened around box boundaries; backticks vanish."""
    out = []
    comment_open = mono_open = False
    for p in range(run.start, run.end):
        if p > run.start:
            out.extend(tex_mark(m) for m in marks.get(p, ()))
        style, c = line.styles[p], line.text[p]
        if style == BACKTICK:  # not rendered; closes monospace text
            if mono_open:
                out.append("}")
                mono_open = False
            continue
        if style != CODE and not comment_open:
            # Inside a box keep the box colors; only switch to the comment font.
            out.append(r"\textsf{" if in_box else r"\sporkComment{")
            comment_open = True
        if (style == MONO) != mono_open:
            out.append(r"\texttt{" if style == MONO else "}")
            mono_open = not mono_open
        out.append(c if style == MATH else _TEX_ESCAPES.get(c, c))
    if mono_open:
        out.append("}")
    if comment_open:
        out.append("}")
    return "".join(out)


def tex_line(line: RenderLine) -> str:
    """TeX for the content of one line (without the per-line wrapper)."""

    def run_tex(run: _Run, marks) -> str:
        if run.color == ELIDE:
            return rf"\sporkComment{{{ELLIPSIS}}}"
        body = _tex_chars(line, run, marks, in_box=run.color is not None)
        if run.color is None:
            return body
        return rf"\sporkListingBox{{{COLOR_MACROS[run.color]}}}{{{body}}}"

    tex = "".join(_walk(line, run_tex, tex_mark))
    if line.kind == "placeholder":
        tex = rf"\textit{{{tex}}}"
    if line.bold:
        tex = rf"\textbf{{{tex}}}"
    return tex


def _version_list(versions) -> str:
    return ",".join(str(v) for v in versions)


TEX_HEADER = """\
%% Generated by code_to_tex (python3 -m code_to_tex) from {source}; do not edit.
%% Instructions for AI coding assistants: this file is hard to read.
%% Read {name}.N.txt (plain text of version N) or {name}.N.dbg (text plus
%% formatting annotations) in this directory instead; tell the user if missing.
%% Use it with \\sporkListing{{{name}}} (see code_to_tex/README.md).
"""


def tex_file(layout: ListingLayout, source_name: str) -> str:
    """All versions of a listing in one file of \\sporkListingRow rows."""
    # Rows = union over versions of the shown items, in source order (every
    # item has its own line number).  id(item) -> version -> line.
    rows: dict[int, dict[int, RenderLine]] = defaultdict(dict)
    for v, lines in enumerate(layout.versions):
        for line in lines:
            rows[id(line.item)][v] = line
    order = sorted(rows, key=lambda key: next(iter(rows[key].values())).item.lineno)

    out = [TEX_HEADER.format(source=source_name, name=layout.name)]
    out.append(rf"\sporkListingBegin{{{layout.name}}}{{{layout.count}}}" + "\n")
    for key in order:
        by_version = rows[key]
        versions = sorted(by_version)
        if next(iter(by_version.values())).kind == "filbreak":
            out.append(rf"\sporkListingFilbreak{{{_version_list(versions)}}}" + "\n")
            continue
        variants: dict[str, list[int]] = {}
        for v in versions:
            variants.setdefault(tex_line(by_version[v]), []).append(v)
        out.append(rf"\sporkListingRow{{{_version_list(versions)}}}{{%" + "\n")
        for tex, vs in variants.items():
            out.append(rf"  \sporkListingVariant{{{_version_list(vs)}}}{{{tex}}}%" + "\n")
        out.append("}\n")
    out.append(r"\sporkListingEnd" + "\n")
    return "".join(out)


# ---------------------------------------------------------------------------
# Plain text and debug text
# ---------------------------------------------------------------------------


def txt_line(line: RenderLine) -> Optional[str]:
    """Displayed text (elisions shown as ...); None for filbreaks."""
    if line.kind == "filbreak":
        return None
    return "".join(
        ELLIPSIS if run.color == ELIDE else line.text[run.start:run.end] for run in _runs(line)
    )


def dbg_mark(mark: MarkDirective) -> str:
    extra = "".join(f" {k}={v}" for k, v in (("xshift", mark.xshift), ("yshift", mark.yshift)) if v)
    return f"⟦@{mark.name}{extra}⟧"


_DBG_KIND_TAGS = {
    ("remark", False): "remark",
    ("remark", True): "remark!",
    ("summary", False): "summary",
    ("summary", True): "summary!",
    ("placeholder", False): "placeholder",
}


def dbg_line(line: RenderLine) -> str:
    if line.kind == "filbreak":
        return "⟦filbreak⟧"

    def run_dbg(run: _Run, marks) -> str:
        parts = []
        for p in range(run.start, run.end):
            if p > run.start:
                parts.extend(dbg_mark(m) for m in marks.get(p, ()))
            parts.append(line.text[p])
        body = "".join(parts)
        return body if run.color is None else f"⟦{run.color}:{body}⟧"

    text = "".join(_walk(line, run_dbg, dbg_mark))
    tag = _DBG_KIND_TAGS.get((line.kind, line.bold))
    return f"⟦{tag}:{text}⟧" if tag else text


def txt_file(lines: list[RenderLine]) -> str:
    return "".join(t + "\n" for t in map(txt_line, lines) if t is not None)


def dbg_file(lines: list[RenderLine]) -> str:
    return "".join(dbg_line(line) + "\n" for line in lines)
